/**
 * The AI skill kit: a ZIP the user installs once in their own AI tooling
 * so the tool already knows the SolveStack contract. Generated entirely
 * from the same constants the in-app prompts use (AGENT_TASKS,
 * AGENT_STANDING_RULES, buildReplyContract) — the kit can never drift
 * from the app. SolveStack hosts nothing and calls no model; the user
 * carries this file like every other pack.
 */
import {
  AGENT_STANDING_RULES,
  AGENT_TASKS,
  agentTaskById,
  buildReplyContract,
} from "./agent-tasks";

const SKILL_MD = `---
name: solvestack-adapter
description: Use when working with a SolveStack agent pack (AGENT.md, session.redacted.json, knowledge.md) or when asked to review, summarize, audit, or draft knowledge from a SolveStack troubleshooting session. Defines the reading order, the evidence rules, the five standard tasks, and the solvestack-reply v1 return format the app can apply.
---

# SolveStack adapter

SolveStack is a local-first troubleshooting workspace. It does not call a
model: a person captures an investigation locally, exports a redacted
**agent pack**, and carries it to you. Your job is to work only from that
record and hand work back in a format the app can apply.

## Reading a pack

1. \`AGENT.md\` — the pack's own rules and contents.
2. \`session.redacted.json\` — the structured record (entries, hypotheses,
   tasks, resolution). Attachment binaries are never included.
3. \`knowledge.md\` — the human-readable summary of the same record.
4. \`PROMPT.md\`, when present — the specific task requested. Its full
   text governs; this skill supplies the standing contract behind it.

## Standing rules

${AGENT_STANDING_RULES}

## The five standard tasks

${AGENT_TASKS.map((task) => `- **${task.id}** — ${task.label}: ${task.description}`).join("\n")}

Full instructions for each task live in \`references/<task-id>.md\` in this
skill folder. When the pack's PROMPT.md names a task, follow that file.

## How to reply (solvestack-reply v1)

${buildReplyContract("<the task's id — one of: review, summarize, kb-article, contradiction, prevention>")}

The task id in the block must be the task you were actually given, and the
sessionId must be copied from the record you were handed.
`;

const README_MD = `# SolveStack AI skill kit

Generated by SolveStack from the same prompts the app itself uses, so the
kit and the app cannot drift apart. Re-export it from SolveStack
(Settings → Portability → AI skill kit) whenever the app updates its
tasks or reply contract.

## What's inside

- \`solvestack-adapter/SKILL.md\` — an Agent Skills folder: what a
  SolveStack agent pack is, the evidence rules, the five standard tasks,
  and the **solvestack-reply v1** format an AI answer should end with so
  SolveStack can apply it (Apply AI reply, in the session toolbar).
- \`solvestack-adapter/references/*.md\` — the full instructions for each
  of the five tasks.

## Using it, per tool

- **Tools that support Agent Skills folders** (Claude and compatible
  clients): add the \`solvestack-adapter\` folder where the tool keeps
  its skills, then just hand it a SolveStack pack — it will follow the
  contract, including the reply block.
- **ChatGPT**: plugins there are directory-curated, so a downloaded kit
  can't be installed as one. The portable path stays the pack itself:
  export an agent pack (or use Open in ChatGPT), and the pack's PROMPT.md
  already carries the full contract. If you keep a project or custom
  instructions for troubleshooting, pasting SKILL.md's text there gives
  the same standing rules.
- **Claude Projects / Copilot / Gemini**: paste SKILL.md as project or
  custom instructions, or attach it alongside the pack. The reply block
  works the same everywhere, because SolveStack — not the tool — parses
  and applies it.

Nothing in this kit connects to SolveStack or sends data anywhere. It is
instructions, all the way down.
`;

export function buildSkillKitFiles(): { name: string; text: string }[] {
  const files: { name: string; text: string }[] = [
    { name: "README.md", text: README_MD },
    { name: "solvestack-adapter/SKILL.md", text: SKILL_MD },
  ];
  for (const task of AGENT_TASKS) {
    const full = agentTaskById(task.id);
    files.push({
      name: `solvestack-adapter/references/${task.id}.md`,
      text: [
        `# ${full.label} (${full.id})`,
        "",
        full.description,
        "",
        "## Instructions",
        "",
        full.instructions,
        "",
        "## Reply guidance",
        "",
        full.replyGuidance,
        "",
      ].join("\n"),
    });
  }
  return files;
}
